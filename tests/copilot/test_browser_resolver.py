def test_resolve_fields_batch(fresh_db):
    store_answer(fresh_db, "Email", "a@b.com")
    store_answer(fresh_db, "How did you hear", "LinkedIn")
    fills = resolve_fields(
        fresh_db,
        [
            field(FieldKind.EMAIL, "Email", field_id="e"),
            field(
                FieldKind.SELECT,
                "How did you hear",
                options=[("linkedin", "LinkedIn")],
                field_id="s",
            ),
        ],
        "ai",
    )
    assert [f.field_id for f in fills] == ["e", "s"]
    assert all(f.filled for f in fills)


