def test_unknown_field_not_filled(fresh_db):
    """No stored answer, no deterministic hit, engine abstains → no fill."""
    ctx = ResolveContext(
        conn=fresh_db,
        profile={},
        hybrid_resolver=lambda q, p: {
            "status": "manual_review",
            "source": "llm",
            "semantic_answer": None,
            "serialized_answer": None,
            "confidence": None,
            "reasoning": "abstain",
        },
        cache={},
    )
    fill = resolve_field(
        fresh_db, field(FieldKind.TEXT, "Cosmic question"), "ai", context=ctx
    )
    assert fill.filled is False
    assert fill.confidence is None


