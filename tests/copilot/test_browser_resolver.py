def test_select_matches_option_label(fresh_db):
    store_answer(fresh_db, "How did you hear about this job?", "LinkedIn")
    fill = resolve_field(
        fresh_db,
        field(
            FieldKind.SELECT,
            "How did you hear about this job?",
            options=[("linkedin", "LinkedIn"), ("referral", "Referral")],
        ),
        "ai",
    )
    assert fill.filled is True
    assert fill.resolution["semantic_answer"] == "LinkedIn"
    assert fill.source == "manual"
    assert fill.confidence == 1.0
    assert fill.resolution["typed_value"] == "linkedin"  # option id


