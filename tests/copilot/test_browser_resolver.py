def field(
    kind,
    label,
    *,
    options=(),
    name="n",
    required=False,
    field_id="f1",
    confidence=1.0,
):
    return TypedField(
        field_id=field_id,
        kind=kind,
        label=label,
        name=name,
        options=tuple(FieldOption(value=v, label=lb) for v, lb in options),
        required=required,
        page=0,
        confidence=confidence,
    )


def store_answer(conn, label, semantic, profile_id="ai", **overrides):
    row = {
        "question_fp": fingerprint(Question(label=label)),
        "profile_id": profile_id,
        "source": "manual",
        "semantic_answer": semantic,
        "serialized_answer": semantic,
        "confidence": 1.0,
        "status": "confirmed",
        "reason": "human",
    }
    row.update(overrides)
    conn.execute(
        "INSERT INTO copilot_answers (question_fp, profile_id, source, "
        "semantic_answer, serialized_answer, confidence, status, reason) "
        "VALUES (:question_fp, :profile_id, :source, :semantic_answer, "
        ":serialized_answer, :confidence, :status, :reason)",
        row,
    )
    conn.commit()


def resolve_hybrid(**overrides):
    result = {
        "status": "resolved",
        "source": "llm",
        "semantic_answer": "generated",
        "serialized_answer": "generated",
        "confidence": 0.97,
        "reasoning": "generated by test engine",
    }
    result.update(overrides)
    return result


