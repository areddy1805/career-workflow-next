"""Unit tests for CP-5-03: field resolver (04 §5).

Contract: label → Answer Bank fingerprint (same key space as the brief path,
D-020) → resolve (06 §3) → type-match (select→option id, radio→value,
date→iso, checkbox→multi, number) → FieldFill {field_id, resolution,
filled, confidence, source, reason}. AC: type matching correct (08 CP-5-03).

Pure unit tests: no browser, no Playwright — TypedField built directly.
"""

